const assert=require('node:assert/strict');const P=require('../cr-publication-core.js');
const now=new Date('2026-11-28T15:00:00Z');const exp=Date.parse('2026-12-15')/1000;
const cr={id:10,Entretien:2,Version:1,Etat:'Brouillon',EC_Habilite_ACL:true,Taille_Texte_Valide_ACL:true,Identifiant_Metier:'SIG-TEST-CR-V01',Texte:'Texte fictif'};
const prep={id:20,Compte_Rendu:10,EC_Habilite_ACL:true,Action:'Preparation',Destinataire_Email:'test@example.invalid',Date_Expiration:exp};
const run=(p=prep,cs=[cr],ps=[prep],es=[],pubs=[])=>P.prepare(p,cs,ps,es,pubs,now);
let n=0;const test=(name,f)=>{f();n++;console.log('OK '+name);};
const payload=run();
test('exact payload',()=>assert.deepEqual(payload,{Preparation_Publication:20,Identifiant_Document:cr.Identifiant_Metier,Version:1,Texte:cr.Texte,Destinataire_Email:prep.Destinataire_Email,Date_Expiration:exp,Actif:true}));
test('date encoded',()=>assert.equal(run({...prep,Date_Expiration:['d',exp]}).Date_Expiration,exp));
test('references encoded',()=>assert.equal(run({...prep,Compte_Rendu:['R','T',10]}).Version,1));
test('expired',()=>assert.throws(()=>run({...prep,Date_Expiration:1})));
test('revoked',()=>assert.throws(()=>run(prep,[cr],[prep],[{Preparation:20}])));
test('habilitation',()=>assert.throws(()=>run({...prep,EC_Habilite_ACL:false})));
test('invalid text',()=>assert.throws(()=>run(prep,[{...cr,Texte:''}])));
test('invalid email',()=>assert.throws(()=>run({...prep,Destinataire_Email:'anon@getgrist.com'})));
test('wrong CR',()=>assert.throws(()=>run({...prep,Compte_Rendu:99})));
test('older version',()=>assert.throws(()=>run(prep,[cr,{...cr,id:11,Version:2}])));
test('duplicate version',()=>assert.throws(()=>run(prep,[cr,{...cr,id:11}])));
test('duplicate publication',()=>assert.throws(()=>run(prep,[cr],[prep],[],[payload])));
test('other preparation same series',()=>assert.throws(()=>run(prep,[cr],[prep,{...prep,id:21}],[],[{Preparation_Publication:21}])));
test('unknown read',()=>assert.throws(()=>run(prep,[cr],[prep],[],null)));
test('confirmed',()=>assert.equal(P.confirmed(payload,[{...payload,Acces_Actif_ACL:true}]),true));
test('not confirmed',()=>assert.equal(P.confirmed(payload,[{...payload,Acces_Actif_ACL:false}]),false));
test('confirmation wrong text',()=>assert.equal(P.confirmed(payload,[{...payload,Texte:'autre',Acces_Actif_ACL:true}]),false));
console.log(`${n} tests réussis`);
